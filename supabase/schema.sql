-- WebBox 云端后台数据库结构。先在 Supabase SQL Editor 中完整执行本文件。
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.sites (
  id bigint generated by default as identity primary key,
  name text not null,
  url text not null,
  category text not null default '默认',
  created_at timestamptz not null default now()
);
create table if not exists public.ad_rules (
  id bigint generated by default as identity primary key,
  domain text not null unique,
  note text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.vpn_links (
  id bigint generated by default as identity primary key,
  name text not null,
  url text not null,
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.sites enable row level security;
alter table public.ad_rules enable row level security;
alter table public.vpn_links enable row level security;
-- 只有 profiles 中被标记为管理员的用户可以读取或修改后台数据。
create or replace function public.is_webbox_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and is_admin=true); $$;
drop policy if exists "admins manage profiles" on public.profiles;
create policy "admins manage profiles" on public.profiles for select to authenticated using (public.is_webbox_admin() or id=auth.uid());
drop policy if exists "admins manage sites" on public.sites;
create policy "admins manage sites" on public.sites for all to authenticated using (public.is_webbox_admin()) with check (public.is_webbox_admin());
drop policy if exists "admins manage ad rules" on public.ad_rules;
create policy "admins manage ad rules" on public.ad_rules for all to authenticated using (public.is_webbox_admin()) with check (public.is_webbox_admin());
drop policy if exists "admins manage vpn links" on public.vpn_links;
create policy "admins manage vpn links" on public.vpn_links for all to authenticated using (public.is_webbox_admin()) with check (public.is_webbox_admin());
